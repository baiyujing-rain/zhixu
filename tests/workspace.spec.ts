import { test, expect } from '@playwright/test';

test('从示例进入引导，切换语言，保存笔记并刷新恢复', async ({ page, request }) => {
  const pageErrors: string[] = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '今天，想通一道题。' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/home-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '两数之和 数组 / 哈希表 简单' }).click();
  await page.waitForURL(/\?session=/);
  const sessionId = new URL(page.url()).searchParams.get('session');
  await expect(page.getByRole('heading', { name: '两数之和', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '给我一个提示', exact: true }).click();
  await expect(page.getByRole('heading', { name: '先把问题说清楚' })).toBeVisible();
  await page.getByRole('button', { name: 'Python', exact: true }).click();
  await expect(page.locator('.code-toolbar .selected')).toHaveText('Python');
  await expect(page.locator('.monaco-editor')).toBeVisible();
  const editor = page.locator('.monaco-editor textarea.inputarea');
  await editor.focus();
  await page.keyboard.press('Control+A');
  await page.keyboard.insertText('# Python 草稿\nclass Solution:\n    pass');
  await page.getByRole('button', { name: '保存代码', exact: true }).click();
  await expect(page.locator('.code-toolbar')).toContainText('已保存');
  await page.getByRole('button', { name: 'C++', exact: true }).click();
  await expect(page.locator('.code-toolbar .selected')).toHaveText('C++');
  await page.getByRole('button', { name: 'Python', exact: true }).click();
  await expect(page.locator('.monaco-editor')).toContainText('Python 草稿');
  await page.getByLabel('题目操作').click();
  await page.getByRole('button', { name: '复盘笔记', exact: true }).click();
  await page.getByRole('textbox', { name: '复盘笔记', exact: true }).fill('返回下标，不能重复使用同一个位置。');
  await page.getByRole('button', { name: '保存笔记' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.reload();
  await expect(page.locator('.code-toolbar .selected')).toHaveText('Python');
  await expect(page.getByRole('heading', { name: '先把问题说清楚' })).toBeVisible();
  await page.getByLabel('题目操作').click();
  await page.getByRole('button', { name: '复盘笔记', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '复盘笔记', exact: true })).toHaveValue('返回下标，不能重复使用同一个位置。');
  await page.keyboard.press('Escape');
  await expect(page.locator('.monaco-editor')).toBeVisible();
  await expect(page.locator('.monaco-editor')).toContainText('Python 草稿');
  await page.screenshot({ path: 'artifacts/work-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '完整题解', exact: false }).click();
  await page.getByRole('button', { name: '查看完整题解' }).click();
  await expect(page.locator('.messages pre code').last()).toContainText('def twoSum');
  expect(pageErrors).toEqual([]);
  await request.delete(`/api/sessions/${sessionId}`);
});

test('移动端和深色模式布局没有横向溢出', async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '今天，想通一道题。' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/home-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '展开菜单' }).click();
  await page.getByRole('button', { name: '切换深色模式' }).click();
  await page.getByRole('button', { name: '收起菜单' }).click();
  await expect(page.locator('.sidebar')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, -200, 0)');
  await page.screenshot({ path: 'artifacts/home-dark-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '有效的括号 字符串 / 栈 简单' }).click();
  await page.waitForURL(/\?session=/);
  const sessionId = new URL(page.url()).searchParams.get('session');
  await page.getByRole('button', { name: '给我一个提示', exact: true }).click();
  await expect(page.getByRole('heading', { name: '先观察配对顺序' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/work-mobile.png', fullPage: true });
  await request.delete(`/api/sessions/${sessionId}`);
});
