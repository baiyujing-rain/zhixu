import { test, expect } from '@playwright/test';

test('任意位置有动态水波，Windows 减少动画下默认仍播放，并可选择跟随系统或关闭', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '今天，想通一道题。' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/ink-home-desktop.png', fullPage: true });
  await expect(page.locator('body')).toHaveCSS('cursor', /brush-cursor\.svg/);
  await page.locator('.page-heading h1').click();
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(page.locator('.ink-impact .ink-ring')).toHaveCount(3);
  await expect.poll(async () => Number(await page.locator('.ink-impact .ink-ring').first().evaluate(el => getComputedStyle(el).opacity))).toBeGreaterThan(.15);
  await page.screenshot({ path: 'artifacts/ink-ripple-desktop.png', animations: 'allow' });
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2500 });
  await page.mouse.click(1430, 1000);
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2500 });
  const records = page.locator('nav .nav-item').filter({ hasText: '做题记录' });
  await records.click();
  await expect(page.getByRole('heading', { name: '走过的题，留下的思路。' })).toBeVisible();
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2000 });
  const home = page.locator('nav .nav-item').filter({ hasText: '学习工作台' });
  await home.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(page.getByRole('heading', { name: '今天，想通一道题。' })).toBeVisible();
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2000 });
  const disabled = page.getByRole('button', { name: '开始拆解题目' });
  await expect(disabled).toBeDisabled();
  const rect = await disabled.boundingBox();
  await page.mouse.click(rect!.x + rect!.width / 2, rect!.y + rect!.height / 2);
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(disabled).toBeDisabled();
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2500 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await records.click();
  await expect(page.getByRole('heading', { name: '走过的题，留下的思路。' })).toBeVisible();
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(page.locator('.ink-effects')).toHaveCSS('display', 'block');
  await expect(page.locator('.ink-ring').first()).toHaveCSS('animation-duration', '1.4s');
  const ring = page.locator('.ink-ring').first();
  const start = await ring.evaluate(el => Number(new DOMMatrix(getComputedStyle(el).transform).a));
  await expect.poll(async () => ring.evaluate(el => Number(new DOMMatrix(getComputedStyle(el).transform).a))).toBeGreaterThan(start + .1);
  await page.screenshot({ path: 'artifacts/ink-dynamic-reduced-motion.png' });
  await page.locator('.sidebar .nav-item').filter({ hasText: '学习设置' }).click();
  await page.getByRole('button', { name: '跟随系统', exact: true }).click();
  await expect(page.locator('.ink-impact')).toHaveCount(0);
  await page.locator('.page-heading h1').click();
  await expect(page.locator('.ink-impact')).toHaveCount(0);
  await page.getByRole('button', { name: '动态', exact: true }).click();
  await page.locator('.page-heading h1').click();
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.locator('.page-heading h1').click();
  await expect(page.locator('.ink-impact')).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button', { name: '关闭', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(errors).toEqual([]);
});

test('水墨手机与夜墨模式布局清晰，装饰与墨点不会拦截触摸', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  await page.goto((process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:3000') + '/');
  await expect(page.getByRole('heading', { name: '今天，想通一道题。' })).toBeVisible();
  await page.getByRole('heading', { name: '今天，想通一道题。' }).tap();
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2500 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/ink-home-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '展开菜单' }).tap();
  await expect(page.locator('.sidebar')).toHaveClass(/mobile-open/);
  await expect(page.locator('.ink-impact')).toHaveCount(1);
  await page.getByRole('button', { name: '切换深色模式' }).tap();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: '收起菜单' }).tap();
  await expect(page.locator('.sidebar')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, -200, 0)');
  await expect(page.locator('.ink-impact')).toHaveCount(0, { timeout: 2500 });
  await page.screenshot({ path: 'artifacts/ink-home-dark-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await context.close();
});
